import {
  Astronaut,
  HealthReading,
  HealthBaseline,
  HealthAlert,
  WellnessCheckIn,
  MetricType
} from '@/types';
import { METRIC_DEFINITIONS } from '../data/metricDefinitions';

export interface MissionReportSummary {
  reportId: string;
  generatedAt: string;
  astronaut: Astronaut;
  reportingPeriodStart: string;
  reportingPeriodEnd: string;
  totalTelemetryRecords: number;
  simulatedRecordsCount: number;
  importedRecordsCount: number;
  sensorRecordsCount: number;
  metricSummaries: {
    metric: MetricType;
    label: string;
    unit: string;
    sampleCount: number;
    mean: number;
    min: number;
    max: number;
    baselineMean: number;
    differenceFromBaseline: number;
    deviationStatus: string;
  }[];
  alertsTriggered: {
    id: string;
    metric: string;
    severity: string;
    observedValue: number;
    timestamp: string;
    explanation: string;
    acknowledged: boolean;
  }[];
  wellnessOverview: {
    totalEntries: number;
    avgSleepQuality: number;
    avgFatigue: number;
    avgStress: number;
    avgMood: number;
  };
  integrityNotices: string[];
}

export function generateMissionReportSummary(
  astronaut: Astronaut,
  readings: HealthReading[],
  baselines: Record<MetricType, HealthBaseline>,
  alerts: HealthAlert[],
  wellness: WellnessCheckIn[],
  periodDays: number = 7
): MissionReportSummary {
  const now = new Date();
  const periodStart = new Date(now.getTime() - periodDays * 24 * 60 * 60 * 1000);

  // Filter for period and astronaut
  const periodReadings = readings.filter(
    (r) => r.astronautId === astronaut.id && new Date(r.timestamp) >= periodStart
  );
  const periodAlerts = alerts.filter(
    (a) => a.astronautId === astronaut.id && new Date(a.timestamp) >= periodStart
  );
  const periodWellness = wellness.filter(
    (w) => w.astronautId === astronaut.id && new Date(w.timestamp) >= periodStart
  );

  let simulatedCount = 0;
  let importedCount = 0;
  let sensorCount = 0;

  periodReadings.forEach((r) => {
    if (r.source === 'simulated') simulatedCount++;
    else if (r.source === 'imported_csv' || r.source === 'imported_json') importedCount++;
    else sensorCount++;
  });

  const integrityNotices: string[] = [];
  if (simulatedCount > 0) {
    integrityNotices.push(
      `NOTICE: Contains ${simulatedCount} synthetic records generated by STELLAR Mission Data Simulator for demonstration purposes.`
    );
  }
  if (importedCount > 0) {
    integrityNotices.push(`Contains ${importedCount} records imported via CSV/JSON files.`);
  }
  if (periodReadings.length === 0) {
    integrityNotices.push('WARNING: No telemetry records found in the specified reporting window.');
  }

  const metrics: MetricType[] = ['heart_rate', 'spo2', 'sleep_duration', 'activity', 'fatigue', 'stress'];
  const metricSummaries = metrics.map((m) => {
    const def = METRIC_DEFINITIONS[m];
    const mReadings = periodReadings.filter((r) => r.metric === m && r.quality !== 'unreliable');
    const values = mReadings.map((r) => r.value);
    const baseline = baselines[m];
    const baselineMean = baseline ? baseline.referenceMean : 0;

    let mean = 0;
    let min = 0;
    let max = 0;
    if (values.length > 0) {
      mean = Number((values.reduce((a, b) => a + b, 0) / values.length).toFixed(1));
      min = Math.min(...values);
      max = Math.max(...values);
    }

    const diff = Number((mean - baselineMean).toFixed(1));
    let deviationStatus = 'Nominal Alignment';
    if (baseline && baseline.standardDeviation > 0) {
      const z = Math.abs(diff / baseline.standardDeviation);
      if (z >= 2.0) deviationStatus = 'Significant Deviation';
      else if (z >= 1.2) deviationStatus = 'Moderate Variance';
    }

    return {
      metric: m,
      label: def.label,
      unit: def.unit,
      sampleCount: values.length,
      mean,
      min,
      max,
      baselineMean,
      differenceFromBaseline: diff,
      deviationStatus
    };
  });

  // Wellness averages
  const totalEntries = periodWellness.length;
  let avgSleepQuality = 0;
  let avgFatigue = 0;
  let avgStress = 0;
  let avgMood = 0;

  if (totalEntries > 0) {
    avgSleepQuality = Number((periodWellness.reduce((s, w) => s + w.sleepQuality, 0) / totalEntries).toFixed(1));
    avgFatigue = Number((periodWellness.reduce((s, w) => s + w.fatigue, 0) / totalEntries).toFixed(1));
    avgStress = Number((periodWellness.reduce((s, w) => s + w.stress, 0) / totalEntries).toFixed(1));
    avgMood = Number((periodWellness.reduce((s, w) => s + w.mood, 0) / totalEntries).toFixed(1));
  }

  return {
    reportId: `REP-${astronaut.missionId}-${Date.now().toString().slice(-6)}`,
    generatedAt: now.toISOString(),
    astronaut,
    reportingPeriodStart: periodStart.toISOString(),
    reportingPeriodEnd: now.toISOString(),
    totalTelemetryRecords: periodReadings.length,
    simulatedRecordsCount: simulatedCount,
    importedRecordsCount: importedCount,
    sensorRecordsCount: sensorCount,
    metricSummaries,
    alertsTriggered: periodAlerts.map((a) => ({
      id: a.id,
      metric: METRIC_DEFINITIONS[a.metric]?.label || a.metric,
      severity: a.severity,
      observedValue: a.observedValue,
      timestamp: a.timestamp,
      explanation: a.explanation,
      acknowledged: a.acknowledged
    })),
    wellnessOverview: {
      totalEntries,
      avgSleepQuality,
      avgFatigue,
      avgStress,
      avgMood
    },
    integrityNotices
  };
}

/**
 * Exports data table to CSV format.
 */
export function exportReadingsToCsv(readings: HealthReading[]): string {
  const headers = ['id', 'astronautId', 'metric', 'value', 'unit', 'timestamp', 'source', 'quality', 'notes'];
  const rows = readings.map((r) => [
    r.id,
    r.astronautId,
    r.metric,
    r.value,
    r.unit,
    r.timestamp,
    r.source,
    r.quality,
    `"${(r.notes || '').replace(/"/g, '""')}"`
  ]);

  return [headers.join(','), ...rows.map((row) => row.join(','))].join('\n');
}

export function exportAlertsToCsv(alerts: HealthAlert[]): string {
  const headers = ['id', 'astronautId', 'metric', 'severity', 'observedValue', 'baselineValue', 'deviation', 'timestamp', 'acknowledged', 'explanation'];
  const rows = alerts.map((a) => [
    a.id,
    a.astronautId,
    a.metric,
    a.severity,
    a.observedValue,
    a.baselineValue,
    a.deviation,
    a.timestamp,
    a.acknowledged ? 'TRUE' : 'FALSE',
    `"${a.explanation.replace(/"/g, '""')}"`
  ]);

  return [headers.join(','), ...rows.map((row) => row.join(','))].join('\n');
}
